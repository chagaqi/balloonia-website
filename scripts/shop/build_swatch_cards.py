"""Build the colour cards the order Telegram ping sends after the order text.

One JPEG per swatch option (the shop's swatch photo with the colour name printed
under it), so Brenda sees "Pastel Green" as an actual balloon at a glance.
Reads option_sets read-only, then writes:

  public/swatches/<prefix>-<slug>.jpg   served at balloonia.events/swatches/...
  src/lib/shop/swatch-cards.ts          'cartKey|Value' -> file name

Re-run after adding or renaming a swatch option, then commit + push:

  python scripts/shop/build_swatch_cards.py
"""
import io, json, os, re
import psycopg, requests
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, 'public', 'swatches')
MAP = os.path.join(ROOT, 'src', 'lib', 'shop', 'swatch-cards.ts')
env = dict(re.findall(r'^([A-Z0-9_]+)=(.*)$', open(os.path.join(ROOT, '.env'), encoding='utf-8').read(), re.M))

# File prefix + the small line under the name, per swatch field.
KINDS = {'custom_colors': ('color', 'Balloon color'), 'number_color': ('number', 'Number color'),
         'accent_style': ('weight', 'Weight style')}
W, H, BOX = 540, 660, 440
BOLD = 'C:/Windows/Fonts/segoeuib.ttf'
REG = 'C:/Windows/Fonts/segoeui.ttf'


def slug(s):
    return re.sub(r'[^a-z0-9]+', '-', s.lower()).strip('-')


def fit(draw, text, path, size, width):
    while size > 20:
        font = ImageFont.truetype(path, size)
        if draw.textlength(text, font=font) <= width:
            return font
        size -= 2
    return ImageFont.truetype(path, size)


def card(img, name, sub):
    canvas = Image.new('RGB', (W, H), 'white')
    img = img.convert('RGB')
    scale = min(BOX / img.width, BOX / img.height)
    img = img.resize((round(img.width * scale), round(img.height * scale)), Image.LANCZOS)
    canvas.paste(img, ((W - img.width) // 2, 30 + (BOX - img.height) // 2))
    d = ImageDraw.Draw(canvas)
    big = fit(d, name, BOLD, 58, W - 40)
    d.text((W / 2, 520), name, font=big, fill='#1f1a17', anchor='mm')
    d.text((W / 2, 590), sub, font=ImageFont.truetype(REG, 30), fill='#8a817c', anchor='mm')
    return canvas


def main():
    with psycopg.connect(env['POSTGRES_URL'], connect_timeout=30) as c:
        c.execute('set transaction read only')
        sets = c.execute('select key, definition from option_sets order by key').fetchall()
    options = {}
    for _, d in sets:
        d = d if isinstance(d, dict) else json.loads(d)
        for f in d.get('fields') or []:
            if f.get('type') != 'swatches':
                continue
            for o in f.get('options') or []:
                if o.get('image') and o.get('value'):
                    options.setdefault((f['cartKey'], o['value'].strip()), (o['image'], f['label']))
    os.makedirs(OUT, exist_ok=True)
    cards = {}
    for (key, value), (url, label) in sorted(options.items()):
        prefix, sub = KINDS.get(key, (slug(key), re.sub(r'\s*\(.*\)$', '', label)))
        name = f'{prefix}-{slug(value)}.jpg'
        img = Image.open(io.BytesIO(requests.get(url, timeout=30).content))
        card(img, value, sub).save(os.path.join(OUT, name), quality=88, optimize=True)
        cards[f'{key}|{value}'] = name
        print(f'{name:40} <- {value}')
    body = ',\n'.join(f'  {json.dumps(k, ensure_ascii=False)}: {json.dumps(v)}' for k, v in cards.items())
    with open(MAP, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('// Generated by scripts/shop/build_swatch_cards.py. Do not edit by hand.\n'
                 '// "cartKey|option value" -> colour card in public/swatches/.\n'
                 f'export const SWATCH_CARDS: Record<string, string> = {{\n{body},\n}};\n')
    print(f'\n{len(cards)} cards -> {OUT}')


if __name__ == '__main__':
    main()
